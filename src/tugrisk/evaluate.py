"""Simulation study: timing accuracy of the TUG analysis against known ground truth.

Run:  python -m tugrisk.evaluate
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from .simulate import random_protocol, simulate
from .tug import PHASES, STEADI_CUTOFF_S, TugError, analyse

ROOT = Path(__file__).resolve().parents[2]
NOISE_CM = [0, 1, 2, 4, 6]
N_PER_CONDITION = 200


def run_condition(noise_cm: float, fps: float, dropout: float, n: int, seed: int) -> dict:
    rng = np.random.default_rng(seed)
    truth, est, phase_err, failures = [], [], {k: [] for k in PHASES}, 0
    for i in range(n):
        p = random_protocol(rng)
        try:
            r = analyse(simulate(p, fps=fps, noise_m=noise_cm / 100, dropout=dropout,
                                 seed=int(rng.integers(1 << 31))))
        except TugError:
            failures += 1
            continue
        truth.append(p.total)
        est.append(r.total_time)
        d = r.durations()
        for k in PHASES:
            phase_err[k].append(d[k] - (p.truth[k][1] - p.truth[k][0]))
    truth, est = np.asarray(truth), np.asarray(est)
    diff = est - truth
    risk_t, risk_e = truth >= STEADI_CUTOFF_S, est >= STEADI_CUTOFF_S
    tp, fn = int((risk_t & risk_e).sum()), int((risk_t & ~risk_e).sum())
    tn, fp = int((~risk_t & ~risk_e).sum()), int((~risk_t & risk_e).sum())
    return {
        "noise_cm": noise_cm, "fps": fps, "dropout": dropout, "n": n, "failures": failures,
        "bias_s": float(diff.mean()), "sd_s": float(diff.std(ddof=1)),
        "loa_s": [float(diff.mean() - 1.96 * diff.std(ddof=1)), float(diff.mean() + 1.96 * diff.std(ddof=1))],
        "mae_s": float(np.abs(diff).mean()),
        "pearson_r": float(np.corrcoef(truth, est)[0, 1]),
        "sensitivity": tp / (tp + fn) if tp + fn else None,
        "specificity": tn / (tn + fp) if tn + fp else None,
        "confusion": {"tp": tp, "fn": fn, "tn": tn, "fp": fp},
        "phase_mae_s": {k: float(np.abs(v).mean()) for k, v in phase_err.items()},
        "phase_bias_s": {k: float(np.mean(v)) for k, v in phase_err.items()},
        "_truth": truth.tolist(), "_est": est.tolist(),
    }


def main() -> None:
    out = {"cutoff_s": STEADI_CUTOFF_S, "conditions": []}
    seed = 0
    for fps in [30, 15]:
        for noise in NOISE_CM:
            seed += 1
            c = run_condition(noise, fps, 0.05, N_PER_CONDITION, seed)
            out["conditions"].append(c)
            print(f"fps {fps:2d} noise {noise} cm: bias {c['bias_s']:+.2f} s, MAE {c['mae_s']:.2f} s, "
                  f"LoA {c['loa_s'][0]:+.2f} to {c['loa_s'][1]:+.2f}, sens {c['sensitivity']:.3f}, "
                  f"spec {c['specificity']:.3f}, failures {c['failures']}")

    ref = next(c for c in out["conditions"] if c["fps"] == 30 and c["noise_cm"] == 2)
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.9), dpi=140)
    t, e = np.asarray(ref["_truth"]), np.asarray(ref["_est"])
    ax = axes[0]
    ax.scatter((t + e) / 2, e - t, s=10, alpha=.6, color="#0f766e")
    for y, ls in [(ref["bias_s"], "-"), (ref["loa_s"][0], "--"), (ref["loa_s"][1], "--")]:
        ax.axhline(y, color="#111", lw=1, ls=ls)
    ax.set(xlabel="Mean of estimate and truth (s)", ylabel="Estimate - truth (s)",
           title="Bland-Altman, 30 fps, 2 cm noise")
    ax = axes[1]
    for fps, col in [(30, "#0f766e"), (15, "#f59e0b")]:
        cs = [c for c in out["conditions"] if c["fps"] == fps]
        ax.plot([c["noise_cm"] for c in cs], [c["mae_s"] for c in cs], "o-", color=col, label=f"{fps} fps")
    ax.set(xlabel="Landmark noise SD (cm)", ylabel="MAE of total time (s)", title="Robustness to noise")
    ax.legend(frameon=False)
    ax = axes[2]
    ax.bar([k.replace("_", "\n") for k in PHASES], [ref["phase_mae_s"][k] for k in PHASES], color="#0f766e")
    ax.set(ylabel="MAE of phase duration (s)", title="Per-phase error, 30 fps, 2 cm noise")
    for ax in axes:
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    (ROOT / "reports" / "figures").mkdir(parents=True, exist_ok=True)
    fig.savefig(ROOT / "reports" / "figures" / "simulation.png")

    for c in out["conditions"]:
        c.pop("_truth"), c.pop("_est")
    (ROOT / "reports" / "metrics.json").write_text(json.dumps(out, indent=2))

    L = ["# Results: simulation study", "",
         "Generated by `python -m tugrisk.evaluate`. Each row: 200 simulated tests with random phase",
         "durations (total 6 to 30 s), 5% random frame drop-out. Bias = estimate minus truth.", "",
         "| fps | Noise SD (cm) | Bias (s) | 95% limits of agreement (s) | MAE (s) | r | Sens. at 12 s | Spec. at 12 s | Failed |",
         "|---|---|---|---|---|---|---|---|---|"]
    for c in out["conditions"]:
        L.append(f"| {c['fps']} | {c['noise_cm']} | {c['bias_s']:+.2f} | {c['loa_s'][0]:+.2f} to {c['loa_s'][1]:+.2f} | "
                 f"{c['mae_s']:.2f} | {c['pearson_r']:.3f} | {c['sensitivity']:.1%} | {c['specificity']:.1%} | "
                 f"{c['failures']}/{c['n']} |")
    L += ["", "## Phase duration error at 30 fps, 2 cm noise", "", "| Phase | Bias (s) | MAE (s) |", "|---|---|---|"]
    L += [f"| {k} | {ref['phase_bias_s'][k]:+.2f} | {ref['phase_mae_s'][k]:.2f} |" for k in PHASES]
    (ROOT / "reports" / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
